#include<unistd.h>

int	ft_str_is_numeric(char *str)
{
	int	n;
	int	i;

	n = 1;
	i = 0;
	while (str[i] != '\0')
	{
		if (!(str[i] >= '0' && str[i] <= '9'))
			n = 0;
		i++;
	}
	return (n);
}
