#include<unistd.h>

int	ft_str_is_printable(char *str)
{
	int	i;
	int	p;

	p = 1;
	i = 0;
	while (str[i] != '\0')
	{
		if (!(str[i] > 31 && str[i] <= 127))
		{
			p = 0;
		}
		i++;
	}
	return (p);
}
